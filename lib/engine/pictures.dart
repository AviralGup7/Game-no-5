/// The picture library.
///
/// A nonogram's reward is the moment the grid turns into a *thing*. Random
/// noise grids are technically valid puzzles and are what most cheap nonogram
/// apps ship; they are also joyless. So every picture here is hand-authored
/// pixel art, stored as ASCII so it is reviewable in a diff and needs no
/// binary asset, no download, and no licence.
///
/// PURE DART — no Flutter imports.
///
/// `#` = filled, `.` = empty. Rows top to bottom.
///
/// Rules followed while drawing these:
///   * Recognisable at a glance once complete, at arm's length, on a phone.
///   * Avoid single stray pixels far from the mass of the picture — they read
///     as a mistake rather than as detail.
///   * Prefer solid runs: long runs make bigger clue numbers, which are easier
///     to reason about than a row of 1s.
library;

import 'pictures_extra.dart';

class Picture {
  final String name;
  final int size;
  final List<bool> cells;

  const Picture(this.name, this.size, this.cells);

  bool at(int r, int c) => cells[r * size + c];
}

/// Shared builder, also used by `pictures_extra.dart`.
Picture buildPicture(String name, List<String> rows) {
  final size = rows.length;
  for (final r in rows) {
    if (r.length != size) {
      throw StateError('Picture "$name" is not square: row "$r" '
          'is ${r.length} wide but there are $size rows');
    }
  }
  final cells = <bool>[];
  for (final r in rows) {
    for (final ch in r.split('')) {
      cells.add(ch == '#');
    }
  }
  return Picture(name, size, cells);
}

